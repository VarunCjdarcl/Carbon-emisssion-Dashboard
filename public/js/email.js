// Emission certificate compose modal.

const EmailModal = (() => {
  const state = { customer: null, period: null, totals: null };

  function attach() {
    document.querySelectorAll('#emailModal [data-close]').forEach(el => {
      el.addEventListener('click', close);
    });
    document.getElementById('emailForm').addEventListener('submit', onSubmit);
  }

  function open({ customer, period, totals }) {
    state.customer = customer;
    state.period = period || Period.getCurrent();
    state.totals = totals || {};

    const periodLabel = state.period.preset === 'custom'
      ? `${Util.fmtDate(state.period.from)} – ${Util.fmtDate(state.period.till)}`
      : presetText(state.period.preset);

    const form = document.getElementById('emailForm');
    form.to.value = customer.customerEmail || '';
    form.cc.value = '';
    form.subject.value = `Carbon Emission Certificate – ${customer.customerName} – ${periodLabel}`;
    form.body.value = composeDefaultBody(customer, periodLabel, totals);
    document.getElementById('emailStatus').textContent = '';
    document.getElementById('emailStatus').className = 'email-status';
    const attachEl = document.getElementById('emailAttachment');
    if (attachEl) attachEl.textContent = 'Certificate is rendered inline in the email body.';
    document.getElementById('emailModal').hidden = false;
  }

  function presetText(p) {
    return ({
      today: 'Today', yesterday: 'Yesterday', thisWeek: 'This Week', previousWeek: 'Previous Week',
      last7: 'Last 7 Days', thisMonth: 'This Month', previousMonth: 'Previous Month',
      last30: 'Last 30 Days', last2months: 'Last 2 Months', last5months: 'Last 5 Months',
      last1year: 'Last 1 Year', last2years: 'Last 2 Years', custom: 'Custom Range',
    }[p] || p);
  }

  function composeDefaultBody(customer, periodLabel /* totals unused — shown in inline cert */) {
    return `Dear ${customer.customerName} Sustainability Team,

Please find below the Carbon Emission Certificate covering the period ${periodLabel}.

This certificate has been generated by the CJ Darcl Logistics Carbon Emission Tracking System and is based on shipment-level data captured in our TMS. Methodology aligns with the GLEC Framework v3.2 and ISO 14083.

For any questions or to request a custom reporting window, please reply to this email.

Best regards,
CJ Darcl Sustainability Desk`;
  }

  async function onSubmit(e) {
    e.preventDefault();
    const form = e.currentTarget;
    const status = document.getElementById('emailStatus');
    const sendBtn = document.getElementById('emailSendBtn');
    sendBtn.disabled = true;
    status.className = 'email-status'; status.textContent = 'Sending…';

    const period = state.period;
    const payload = {
      customerCode: state.customer.customerCode,
      preset: period.preset || 'thisMonth',
      from: period.preset === 'custom' ? period.from : undefined,
      till: period.preset === 'custom' ? period.till : undefined,
      to: form.to.value.trim(),
      cc: form.cc.value.trim(),
      subject: form.subject.value.trim(),
      body: form.body.value,
    };
    try {
      const res = await Util.api('/api/certificate/send', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
      });
      status.className = 'email-status success';
      status.textContent = res.demo
        ? 'Certificate generated. (Demo SMTP — no email actually sent.)'
        : 'Certificate sent successfully.';
      Util.toast('Certificate dispatched to ' + payload.to, 'success');
      setTimeout(close, 1500);
    } catch (err) {
      status.className = 'email-status error';
      status.textContent = 'Failed: ' + err.message;
      Util.toast(err.message, 'error');
    } finally {
      sendBtn.disabled = false;
    }
  }

  function close() { document.getElementById('emailModal').hidden = true; }

  return { attach, open, close };
})();
